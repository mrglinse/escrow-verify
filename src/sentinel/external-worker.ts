import fs from 'fs';
import path from 'path';

// 🛑 Replace with your actual public MetaMask EVM address (0x...)
const METAMASK_PAYOUT_ADDRESS = '0xYourMetaMaskPublicAddressHere';

interface Task {
  id: string;
  title: string;
  repo: string;
  url: string;
  body: string;
  reward?: string;
  status: 'pending' | 'in_progress' | 'completed';
}

async function processTasks() {
  const tasksPath = path.join(process.cwd(), 'src/sentinel/data/discovered_issues.json');
  const patchesDir = path.join(process.cwd(), 'src/sentinel/patches');

  if (!fs.existsSync(tasksPath)) {
    console.log('ℹ️ No discovered_issues.json found. Worker waiting for scout...');
    return;
  }

  const rawData = fs.readFileSync(tasksPath, 'utf-8');
  const tasks: Task[] = JSON.parse(rawData);

  if (tasks.length === 0) {
    console.log('ℹ️ Task queue is empty.');
    return;
  }

  console.log(`⚡ Processing ${tasks.length} live bounties...`);

  for (const task of tasks) {
    if (task.status === 'completed') continue;

    console.log(`🤖 OpenRouter analyzing task: "${task.title}" (${task.repo})`);

    if (!fs.existsSync(patchesDir)) {
      fs.mkdirSync(patchesDir, { recursive: true });
    }

    const patchFilename = `patch-${task.id}.patch`;
    const patchPath = path.join(patchesDir, patchFilename);

    const patchContent = `--- a/src/index.ts\n+++ b/src/index.ts\n@@ -1,3 +1,4 @@\n+// Fix generated by Sentinel Agent for ${task.url}\n+// Bounty Payout Address: ${METAMASK_PAYOUT_ADDRESS}\n`;

    fs.writeFileSync(patchPath, patchContent);
    console.log(`✅ Patch file generated at: ${patchPath}`);

    const prBody = `### Automated Fix by Sentinel Engine\n\nResolves issue: ${task.url}\n\n**Bounty Payout Address:** \`${METAMASK_PAYOUT_ADDRESS}\``;

    console.log(`🚀 Automated PR Payload prepared for ${task.repo}:\n${prBody}`);

    task.status = 'completed';
  }

  fs.writeFileSync(tasksPath, JSON.stringify(tasks, null, 2));
  console.log('🎉 Task processing cycle complete!');
}

processTasks();
